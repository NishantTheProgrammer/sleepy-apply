async def seed_target_companies(db: AsyncIOMotorDatabase, force_overwrite: bool = False) -> int:
    """Seeds the target companies collection with verified companies and ATS links.

    Uses upsert based on company name to preserve existing fetch counts/custom modifications.
    """
    now = datetime.now(timezone.utc)
    count = 0
    for comp in SEED_COMPANIES:
        update_doc = {
            "$set": {
                "grade": comp["grade"],
                "career_page": comp["career_page"],
                "ats_type": comp["ats_type"],
                "board_token": comp.get("board_token"),
                "api_url": comp.get("api_url"),
                "industry": comp.get("industry"),
                "location_hq": comp.get("location_hq"),
                "updated_at": now,
            },
            "$setOnInsert": {
                "name": comp["name"],
                "is_active": comp.get("is_active", True),
                "total_jobs_fetched": 0,
                "last_fetched_at": None,
                "created_at": now,
            },
        }
        if force_overwrite:
            update_doc["$set"]["is_active"] = comp.get("is_active", True)
            update_doc["$setOnInsert"].pop("is_active", None)

        await db.companies.update_one(
            {"name": comp["name"]},
            update_doc,
            upsert=True,
        )
        count += 1

    logger.info("Target companies seeded", count=count)
    return count


async def main():
    await connect_db()
    db = get_db()
    await seed_target_companies(db)
    total = await db.companies.count_documents({})
    tier1 = await db.companies.count_documents({"grade": "Tier-1"})
    tier2 = await db.companies.count_documents({"grade": "Tier-2"})
    tier3 = await db.companies.count_documents({"grade": "Tier-3"})
    print(f"✅ Seeding complete. Total companies in db.companies: {total}")
    print(f"   Tier-1: {tier1} | Tier-2: {tier2} | Tier-3: {tier3}")


if __name__ == "__main__":
    asyncio.run(main())
